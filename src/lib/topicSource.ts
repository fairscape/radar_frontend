/**
 * Where a topic came from, for the topic lists. ``null`` is OpenAlex's own
 * assignment to a seed; ``umls`` is mapped from a seed's UMLS concepts
 * (with ``llm``, the only topics an unpublished paper brings: none are read
 * from a PDF's text since 2026-11-04, rag_lib/content_topics.py);
 * ``researcher`` was declared on the
 * researcher's own profile and no seed carries it (rag_lib/researcher_topics.py);
 * ``llm`` is mapped from a research topic Claude generated (rag_lib/llm_topics.py).
 */
export function topicSourceTag(source: string | null | undefined): string | null {
  if (source === 'umls') return 'UMLS';
  // Guessed from an uploaded PDF's text until 2026-11-04: no longer made,
  // but a saved interest keeps its old ones until its topics are rebuilt.
  if (source === 'pdf_content') return 'PDF (old)';
  if (source === 'researcher') return 'PROFILE';
  if (source === 'prosopia') return 'PROSOPIA';
  if (source === 'llm') return 'LLM';
  return null;
}

export function topicSourceLabel(source: string | null | undefined, llmLabel?: string | null, umlsConcept?: string | null): string {
  if (source === 'umls') return umlsConcept ? `mapped via UMLS from the concept "${umlsConcept}"` : 'mapped via UMLS';
  if (source === 'llm') return llmLabel ? `mapped from the research topic "${llmLabel}" (generated by Claude)` : 'mapped from a research topic Claude generated';
  if (source === 'pdf_content') return "read from an uploaded PDF's text (no longer done); removed the next time this interest's topics are saved";
  if (source === 'researcher') return "declared on the researcher's profile (no seed carries it)";
  if (source === 'prosopia') return 'a Prosopia interest (no seed carries it)';
  if (source === 'adopted') return "kept from the profile of a researcher since forgotten";
  return 'OpenAlex topic';
}

/** How the researcher's profile reads on a topic, for a title or a note. */
export function topicProfileNote(profile: string | null | undefined): string | null {
  if (profile === 'interest') return "an interest on the researcher's profile";
  if (profile === 'not_interest') return "not wanted, per the researcher's profile";
  return null;
}
